#!/usr/bin/env bash
# Regenerates the committed GDScript protobuf codecs with the pinned godobuf.
#   proto/v1/protocol.proto                   -> client/src/net/proto/protocol_v1_pb.gd
#   client/src/net/host/loadtest_state.proto  -> client/src/net/host/loadtest_state_pb.gd (load test only)
# Not wired into `make proto` / proto-codegen-check yet (follow-up).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# shellcheck disable=SC1091
source "$ROOT/tools/versions.env"
GODOT="${GODOT:-godot}"
SHA256="cea865fb0479f8227dc5b22dbdfe4b61ac5be691f6b316a3ea99c0e2764301fc"  # v0.7.0 source tarball
DIR="$ROOT/.tools/godobuf-${GODOBUF_VERSION#v}"  # the tarball unpacks to godobuf-0.7.0
if [ ! -f "$DIR/addons/godobuf/godobuf_cmdln.gd" ]; then
  mkdir -p "$ROOT/.tools"
  tgz="$ROOT/.tools/godobuf-$GODOBUF_VERSION.tar.gz"
  curl -fsSL -o "$tgz" "https://github.com/oniksan/godobuf/archive/refs/tags/$GODOBUF_VERSION.tar.gz"
  echo "$SHA256  $tgz" | sha256sum -c -
  tar -xzf "$tgz" -C "$ROOT/.tools"
fi
gen() {  # gen <src.proto relative to ROOT> <out.gd relative to ROOT>
  local src="$1" out="$2" name
  name="$(basename "$src")"
  cp "$ROOT/$src" "$DIR/$name"
  mkdir -p "$DIR/out"
  (cd "$DIR" && "$GODOT" --headless -s addons/godobuf/godobuf_cmdln.gd --input="$name" --output="out/$name.gd" >/dev/null 2>&1)
  test -s "$DIR/out/$name.gd"
  # godobuf v0.7.0 does not avoid names that collide in Godot 4.7.2:
  #  - field instance_id makes get_instance_id(), which overrides
  #    Object.get_instance_id() (a parse error by default), and
  #  - message Error shadows the global Error enum.
  # Rename both in the generated GDScript only; the wire format uses field
  # numbers, so this does not change the encoding.
  sed -i -E \
    -e 's/func get_instance_id\(\) -> int:/func get_instance_id_value() -> int:/' \
    -e 's/^class Error:/class ErrorMsg:/' \
    -e 's/-> Error:/-> ErrorMsg:/' \
    -e 's/= Error\.new\(\)/= ErrorMsg.new()/' \
    "$DIR/out/$name.gd"
  { echo "# GENERATED by godobuf $GODOBUF_VERSION (https://github.com/oniksan/godobuf) from $src. Do not edit."
    echo "# Regenerate with tools/loadtest/gen-gdscript-proto.sh."
    cat "$DIR/out/$name.gd"; } > "$ROOT/$out"
  echo "generated $out"
}
gen proto/v1/protocol.proto client/src/net/proto/protocol_v1_pb.gd
gen client/src/net/host/loadtest_state.proto client/src/net/host/loadtest_state_pb.gd
